const sscCalendarUrl = "https://ssc.gov.in/api/attachment/uploads/masterData/ExamCalendar/Tentative_Calendar2026_27_08012026.pdf";

function sscCalendarExam(value: {
  slug: string;
  title: string;
  shortTitle: string;
  aliases: string[];
  sector: string;
  examTypes: Exam["examTypes"];
  education: Exam["education"];
  statusLabel: string;
  nextAction: string;
  summary: string;
  timeline?: Exam["timeline"];
  noticeUrl?: string;
  sourceTitle?: string;
  sourcePublished?: string;
  statusTone?: Exam["status"]["tone"];
  detail?: string;
  /**
   * Optional sourced detail. Anything supplied here must name the permanent or
   * previous-cycle official document it comes from, because the current cycle
   * has not published a detailed notice.
   */
  age?: string;
  qualification?: string;
  fee?: string;
  pay?: string;
  eligibility?: string[];
  selectionStages?: string[];
  syllabus?: string[];
  keywords?: string[];
  extraLinks?: Exam["officialLinks"];
}) {
  return listedExam({
    slug: value.slug,
    title: value.title,
    shortTitle: value.shortTitle,
    aliases: value.aliases,
    organisation: "Staff Selection Commission",
    governmentLevel: "Central",
    jurisdiction: "All India",
    cycle: "2026–27",
    year: 2026,
    sector: value.sector,
    examTypes: value.examTypes,
    education: value.education,
    status: {
      label: value.statusLabel,
      tone: value.statusTone ?? (value.timeline?.length ? "blue" : "violet"),
      nextAction: value.nextAction,
      detail: value.detail ?? "The cycle is listed in SSC’s official 2026–27 tentative calendar; the detailed notice controls every exact field.",
    },
    summary: value.summary,
    timeline: value.timeline ?? [],
    age: value.age,
    qualification: value.qualification,
    fee: value.fee,
    pay: value.pay,
    eligibility: value.eligibility,
    selectionStages: value.selectionStages,
    syllabus: value.syllabus,
    keywords: value.keywords,
    officialLinks: [
      ...(value.noticeUrl ? [{ label: "Official detailed notice", url: value.noticeUrl, type: "notice" as const }] : []),
      ...(value.extraLinks ?? []),
      { label: "SSC 2026–27 calendar PDF", url: sscCalendarUrl, type: "calendar" },
      { label: "SSC official website", url: "https://ssc.gov.in/", type: "website" },
    ],
    sourceTitle: value.sourceTitle ?? "SSC Tentative Calendar of Examinations 2026–27",
    sourceUrl: value.noticeUrl ?? sscCalendarUrl,
    sourcePublished: value.sourcePublished ?? "8 Jan 2026",
    lastVerified: "4 Aug 2026, 15:05 IST",
  });
}

